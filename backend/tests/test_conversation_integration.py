class TestSessionCreationIntegration:
    def test_new_session_generates_topic_and_sample_and_persists_one_row(self, learner, openrouter):
        level_update = learner.patch(PROFILE_URL, {"level": "B2"}, format="json")
        assert level_update.status_code == 200, level_update.data

        response = learner.post(SESSIONS_URL, {"topic_hint": "travel"}, format="json")

        assert response.status_code == 201, response.data
        session = Session.objects.get()
        assert session.user_id == user_id(LEARNER)
        assert session.title == TOPIC_PAYLOAD["title"]
        assert session.topic == TOPIC_PAYLOAD["description"]
        assert session.topic_hint == "travel"
        assert session.learning_level == "B2"
        data = response.data
        assert data["id"] == session.id
        assert data["title"] == TOPIC_PAYLOAD["title"]
        assert data["topic"] == TOPIC_PAYLOAD["description"]
        assert data["topic_hint"] == "travel"
        assert data["learning_level"] == "B2"
        assert list(data["sample_conversation"]["turns"]) == SAMPLE_PAYLOAD["turns"]
        # The sample conversation is display data only — never chat history.
        assert Message.objects.count() == 0

        # The topic request carried the profile level and the learner's hint,
        # and the sample request was built from the generated topic.
        topic_request, sample_request = openrouter.complete_requests
        assert [m.role for m in topic_request.messages] == ["system", "user"]
        assert "travel" in topic_request.messages[-1].content
        assert "B2" in topic_request.messages[-1].content
        assert [m.role for m in sample_request.messages] == ["system", "user"]
        assert TOPIC_PAYLOAD["title"] in sample_request.messages[-1].content

    def test_created_session_appears_in_the_owner_listing(self, learner, openrouter):
        created = create_session(learner, topic_hint="travel")

        response = learner.get(SESSIONS_URL, format="json")

        assert response.status_code == 200
        assert response.data["count"] == 1
        assert [item["id"] for item in response.data["results"]] == [created["id"]]

    def test_empty_hint_lets_the_ai_choose_the_topic(self, learner, openrouter):
        response = learner.post(SESSIONS_URL, {}, format="json")

        assert response.status_code == 201, response.data
        assert response.data["topic_hint"] == ""
        assert response.data["learning_level"] == "AUTO"
        session = Session.objects.get()
        assert session.topic_hint == ""
        assert session.learning_level == "AUTO"
        user_prompt = openrouter.complete_requests[0].messages[-1].content
        assert "no preference" in user_prompt

    def test_topic_generation_failure_persists_no_session(self, learner, openrouter):
        openrouter.completions.clear()
        openrouter.queue_completion(
            LLMAvailabilityError("upstream unavailable", provider="openrouter")
        )

        response = learner.post(SESSIONS_URL, {"topic_hint": "travel"}, format="json")

        assert response.status_code == 503
        assert "detail" in response.data
        assert Session.objects.count() == 0

    def test_sample_generation_failure_persists_no_session(self, learner, openrouter):
        openrouter.completions.clear()
        openrouter.queue_completion(completion(TOPIC_PAYLOAD))
        openrouter.queue_completion(LLMAuthenticationError("bad key", provider="openrouter"))

        response = learner.post(SESSIONS_URL, {}, format="json")

        assert response.status_code == 502
        assert Session.objects.count() == 0


