def register_and_login(api_client: APIClient, *, username: str, email: str) -> dict:
    """Register a fresh user through the API and return their token payload."""
    registered = api_client.post(
        REGISTER_URL,
        {"username": username, "email": email, "password": PASSWORD},
        format="json",
    )
    assert registered.status_code == 201, registered.data
    logged_in = api_client.post(
        LOGIN_URL, {"username": username, "password": PASSWORD}, format="json"
    )
    assert logged_in.status_code == 200, logged_in.data
    return logged_in.data


