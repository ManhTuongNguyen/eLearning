class TestRetryIntegration:
    def test_retry_replaces_a_failed_generation_in_place(self, learner, openrouter, session):
        openrouter.stream_script = LLMAvailabilityError("upstream collapsed", provider="openrouter")
        failed = read_frames(
            learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json")
        )
        assert failed[-1][0] == "error"
        assistant_id = messages_payload(learner, session["id"])[1]["id"]

        openrouter.stream_script = SUCCESS_SCRIPT
        response = learner.post(retry_url(session["id"], assistant_id))

        assert response.status_code == 200
        frames = read_frames(response)
        assert frames[0] == ("start", {"model": MODEL})
        assert frames[-1] == (
            "completed",
            {"text": COMPLETED_TEXT, "model": MODEL, "delta_count": 2},
        )

        rows = messages_payload(learner, session["id"])
        assert len(rows) == 2
        assert rows[0]["content"] == USER_TEXT
        assert rows[1]["id"] == assistant_id
        assert rows[1]["status"] == "complete"
        assert rows[1]["content"] == COMPLETED_TEXT

        # The retry rebuilt the turn from the same stored prompt.
        assert len(openrouter.stream_requests) == 2
        assert openrouter.stream_requests[1].messages[-1].content == USER_TEXT

    def test_repeated_failures_stay_retryable_until_the_stream_succeeds(
        self, learner, openrouter, session
    ):
        openrouter.stream_script = LLMAvailabilityError("still down", provider="openrouter")
        first_turn = read_frames(
            learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json")
        )
        assert first_turn[-1][0] == "error"
        assistant_id = messages_payload(learner, session["id"])[1]["id"]

        first_retry = learner.post(retry_url(session["id"], assistant_id))
        assert read_frames(first_retry)[-1][0] == "error"

        openrouter.stream_script = SUCCESS_SCRIPT
        second_retry = learner.post(retry_url(session["id"], assistant_id))
        assert read_frames(second_retry)[-1][0] == "completed"

        rows = messages_payload(learner, session["id"])
        assert len(rows) == 2
        assert rows[1]["status"] == "complete"

    def test_successful_assistant_messages_cannot_be_retried(self, learner, openrouter, session):
        openrouter.stream_script = SUCCESS_SCRIPT
        read_frames(learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json"))
        assistant_id = messages_payload(learner, session["id"])[1]["id"]
        stream_calls = len(openrouter.stream_requests)

        response = learner.post(retry_url(session["id"], assistant_id))

        assert response.status_code == 409
        assert len(openrouter.stream_requests) == stream_calls
        assert len(messages_payload(learner, session["id"])) == 2


