def completion(payload: dict) -> CompletionResponse:
    """Build a fake provider completion carrying one JSON payload."""
    return CompletionResponse(text=json.dumps(payload), model=MODEL)


def failing_stream(prefix: tuple[StreamEvent, ...], error: Exception) -> Iterator[StreamEvent]:
    """Emit the prefix events, then fail exactly like a collapsing stream."""
    yield from prefix
    raise error


class FakeOpenRouterProvider(LLMProvider):
    """Scripted OpenRouter stand-in recording every request it receives."""

    def __init__(self) -> None:
        self.completions: deque[CompletionResponse | Exception] = deque()
        self.complete_requests: list[CompletionRequest] = []
        self.stream_script: object = ()
        self.stream_requests: list[CompletionRequest] = []
        self.stream_emitted: list[StreamEvent] = []

    def queue_completion(self, outcome: CompletionResponse | Exception) -> None:
        self.completions.append(outcome)

    def complete(self, request: CompletionRequest) -> CompletionResponse:
        self.complete_requests.append(request)
        outcome = self.completions.popleft()
        if isinstance(outcome, Exception):
            raise outcome
        return outcome

    def stream(self, request: CompletionRequest) -> Iterator[StreamEvent]:
        self.stream_requests.append(request)
        if isinstance(self.stream_script, Exception):
            raise self.stream_script
        for event in self.stream_script:
            self.stream_emitted.append(event)
            yield event


