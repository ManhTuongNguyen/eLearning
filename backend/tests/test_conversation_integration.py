class TestOwnershipIntegration:
    def test_stranger_cannot_access_any_part_of_the_learners_conversation(
        self, learner, stranger, openrouter, session
    ):
        openrouter.stream_script = SUCCESS_SCRIPT
        read_frames(learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json"))
        rows = messages_payload(learner, session["id"])
        assistant_id = rows[1]["id"]

        detail = stranger.get(detail_url(session["id"]), format="json")
        messages = stranger.get(messages_url(session["id"]), format="json")
        streaming = stranger.post(
            stream_url(session["id"]), {"text": "hello from the outside"}, format="json"
        )
        retry = stranger.post(retry_url(session["id"], assistant_id))
        listing = stranger.get(SESSIONS_URL, format="json")

        assert detail.status_code == 404
        assert messages.status_code == 404
        assert streaming.status_code == 404
        assert retry.status_code == 404
        assert listing.status_code == 200
        assert listing.data["results"] == []
        # Nothing was written and no LLM call happened for the stranger.
        assert len(openrouter.stream_requests) == 1
        assert Message.objects.count() == 2
        assert messages_payload(learner, session["id"])[1]["content"] == COMPLETED_TEXT

    def test_missing_sessions_are_indistinguishable_from_foreign_ones(
        self, learner, stranger, openrouter
    ):
        create_session(learner, topic_hint="travel")

        missing_detail = stranger.get(detail_url(99999), format="json")
        missing_messages = stranger.get(messages_url(99999), format="json")
        missing_stream = stranger.post(stream_url(99999), {"text": "hi"}, format="json")

        assert missing_detail.status_code == 404
        assert missing_messages.status_code == 404
        assert missing_stream.status_code == 404
        assert openrouter.stream_requests == []
        assert Message.objects.count() == 0

    def test_anonymous_requests_are_rejected_across_the_conversation_api(
        self, learner, openrouter, session
    ):
        openrouter.stream_script = SUCCESS_SCRIPT
        read_frames(learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json"))
        assistant_id = messages_payload(learner, session["id"])[1]["id"]
        anonymous = APIClient()

        assert anonymous.get(SESSIONS_URL, format="json").status_code == 401
        assert anonymous.post(SESSIONS_URL, {}, format="json").status_code == 401
        assert anonymous.get(detail_url(session["id"]), format="json").status_code == 401
        assert anonymous.get(messages_url(session["id"]), format="json").status_code == 401
        assert (
            anonymous.post(stream_url(session["id"]), {"text": "x"}, format="json").status_code
            == 401
        )
        assert anonymous.post(retry_url(session["id"], assistant_id)).status_code == 401
        assert Message.objects.count() == 2
