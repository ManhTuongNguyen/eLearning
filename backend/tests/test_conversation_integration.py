class TestStreamingChatLifecycle:
    def test_streamed_turn_is_delivered_and_persists_both_messages(
        self, learner, openrouter, session
    ):
        openrouter.stream_script = SUCCESS_SCRIPT

        response = learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json")

        assert response.status_code == 200
        frames = read_frames(response)
        assert frames[0] == ("start", {"model": MODEL})
        assert [name for name, _ in frames[1:-1]] == ["delta", "delta"]
        assert frames[-1] == (
            "completed",
            {"text": COMPLETED_TEXT, "model": MODEL, "delta_count": 2},
        )

        rows = messages_payload(learner, session["id"])
        assert [(row["sequence"], row["role"], row["status"]) for row in rows] == [
            (1, "user", "complete"),
            (2, "assistant", "complete"),
        ]
        assert rows[0]["content"] == USER_TEXT
        assert rows[1]["content"] == COMPLETED_TEXT

    def test_llm_request_carries_topic_and_the_current_message(self, learner, openrouter, session):
        openrouter.stream_script = SUCCESS_SCRIPT

        read_frames(learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json"))

        (request,) = openrouter.stream_requests
        assert [m.role for m in request.messages] == ["system", "user"]
        assert TOPIC_PAYLOAD["title"] in request.messages[0].content
        assert TOPIC_PAYLOAD["description"] in request.messages[0].content
        assert request.messages[-1].content == USER_TEXT

    def test_chunks_arrive_incrementally(self, learner, openrouter, session):
        start = StreamStart(model=MODEL)
        delta_one = StreamDelta(text="Of course!")
        delta_two = StreamDelta(text=" Let us practise.")
        openrouter.stream_script = (start, delta_one, delta_two)

        response = learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json")
        frames = response.streaming_content

        assert parse_frame(next(frames)) == ("start", {"model": MODEL})
        assert openrouter.stream_emitted == [start]
        assert parse_frame(next(frames)) == ("delta", {"text": "Of course!"})
        assert openrouter.stream_emitted == [start, delta_one]
        assert parse_frame(next(frames)) == ("delta", {"text": " Let us practise."})
        assert openrouter.stream_emitted == [start, delta_one, delta_two]
        assert parse_frame(next(frames))[0] == "completed"
        with pytest.raises(StopIteration):
            next(frames)

    def test_second_turn_extends_the_llm_context_with_history(self, learner, openrouter, session):
        openrouter.stream_script = SUCCESS_SCRIPT
        read_frames(learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json"))

        follow_up = "And how do I pay for it?"
        openrouter.stream_script = (StreamStart(model=MODEL), StreamDelta(text="By card!"))
        read_frames(learner.post(stream_url(session["id"]), {"text": follow_up}, format="json"))

        assert len(openrouter.stream_requests) == 2
        second = openrouter.stream_requests[1]
        assert [m.role for m in second.messages] == ["system", "user", "assistant", "user"]
        contents = [m.content for m in second.messages]
        assert USER_TEXT in contents
        assert COMPLETED_TEXT in contents
        assert contents[-1] == follow_up
        rows = messages_payload(learner, session["id"])
        assert [(row["sequence"], row["role"]) for row in rows] == [
            (1, "user"),
            (2, "assistant"),
            (3, "user"),
            (4, "assistant"),
        ]

    def test_failed_generation_persists_the_user_message_and_a_retryable_row(
        self, learner, openrouter, session
    ):
        openrouter.stream_script = LLMAvailabilityError("upstream collapsed", provider="openrouter")

        response = learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json")

        frames = read_frames(response)
        assert [name for name, _ in frames] == ["error"]
        (error_name, error_data) = frames[-1]
        assert error_name == "error"
        assert "upstream collapsed" in error_data["error"]
        assert error_data["retryable"] is True
        assert set(error_data) == {"error", "retryable"}
        rows = messages_payload(learner, session["id"])
        assert [(row["sequence"], row["role"], row["status"]) for row in rows] == [
            (1, "user", "complete"),
            (2, "assistant", "failed"),
        ]
        assert rows[1]["content"] == ""

    def test_mid_stream_failure_never_persists_partial_output(self, learner, openrouter, session):
        error = LLMAvailabilityError("connection reset", provider="openrouter")
        openrouter.stream_script = failing_stream(
            (StreamStart(model=MODEL), StreamDelta(text=STREAMED_TEXT)), error
        )

        response = learner.post(stream_url(session["id"]), {"text": USER_TEXT}, format="json")
        frames = read_frames(response)

        assert [name for name, _ in frames[:2]] == ["start", "delta"]
        assert frames[-1][0] == "error"
        rows = messages_payload(learner, session["id"])
        assert rows[1]["status"] == "failed"
        assert STREAMED_TEXT not in rows[1]["content"]

    def test_blank_text_is_rejected_before_any_write_or_llm_call(
        self, learner, openrouter, session
    ):
        response = learner.post(stream_url(session["id"]), {"text": "   "}, format="json")

        assert response.status_code == 400
        assert "text" in response.data
        assert openrouter.stream_requests == []
        assert Message.objects.count() == 0


